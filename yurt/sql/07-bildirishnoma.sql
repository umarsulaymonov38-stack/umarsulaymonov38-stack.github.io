alter table public.push_queue enable row level security;
grant select on public.push_queue to authenticated;
drop policy if exists push_queue_read on public.push_queue;
create policy push_queue_read on public.push_queue for select to authenticated
  using (user_id = auth.uid() or public.yk_role() = 'admin');

-- Farzandga ulangan ota-onalarga xabarni navbatga qo'yish
create or replace function public.yk_push_add(p_kind text, p_sid text, p_ts timestamptz) returns void
language plpgsql security definer set search_path = public as $$
declare c public.push_config; nm text; tm text := to_char(p_ts at time zone 'Asia/Tashkent', 'HH24:MI');
begin
  select * into c from public.push_config where id = 1;
  if c.id is null or not (case p_kind when 'keldi' then c.on_keldi when 'kelmadi' then c.on_kelmadi when 'ketdi' then c.on_ketdi else false end) then return; end if;
  select array_to_string((regexp_split_to_array(btrim(s.full_name), '\s+'))[1:2], ' ') into nm from public.students s where s.id::text = p_sid;
  insert into public.push_queue (user_id, kind, student_id, title, body, day)
  select u.uid, p_kind, p_sid,
         case p_kind when 'keldi' then '✅ Maktabga keldi' when 'kelmadi' then '❌ Bugun maktabga kelmadi' else '🏠 Maktabdan chiqdi' end,
         nm || case p_kind when 'keldi' then ' bugun maktabga keldi (davomat ' || tm || ' da belgilandi).'
                           when 'kelmadi' then ' bugun maktabga kelmadi. Sababini sinf rahbariga xabar bering.'
                           else ' soat ' || tm || ' da maktabdan chiqdi.' end,
         (p_ts at time zone 'Asia/Tashkent')::date
    from (select sp.claimed_by uid from public.student_private sp where sp.student_id::text = p_sid and sp.claimed_by is not null
          union select p.id from public.profiles p where p.role = 'parent' and p.student_id::text = p_sid) u
   where exists (select 1 from public.push_subs x where x.user_id = u.uid)
  on conflict (user_id, kind, student_id, day) do update
    set status = 'navbat', created_at = now(), tries = 0, error = null
    where public.push_queue.status = 'bekor';
end $$;
revoke all on function public.yk_push_add(text, text, timestamptz) from public, anon, authenticated;

-- 5. Davomat belgilanganda (faqat bugungi kun uchun): keldi / kelmadi. Teskarisi hali yuborilmagan bo'lsa — bekor qilinadi.
create or replace function public.yk_push_att() returns trigger
language plpgsql security definer set search_path = public as $$
declare t date := (now() at time zone 'Asia/Tashkent')::date; k text;
begin
  if new.day <> t or new.att is null then return new; end if;
  if tg_op = 'UPDATE' and new.att is not distinct from old.att and coalesce(new.excused, false) = coalesce(old.excused, false) then return new; end if;
  k := case when new.att = 1 then 'keldi' when coalesce(new.excused, false) then null else 'kelmadi' end;
  update public.push_queue set status = 'bekor'
   where student_id = new.student_id::text and day = t and status = 'navbat'
     and kind in ('keldi', 'kelmadi') and kind is distinct from k;
  if k is not null then perform public.yk_push_add(k, new.student_id::text, now()); end if;
  return new;
exception when others then
  raise warning 'push: %', sqlerrm;  -- bildirishnomadagi xato davomat saqlanishiga to'sqinlik qilmasin
  return new;
end $$;
drop trigger if exists yk_push_att on public.daily_scores;
create trigger yk_push_att after insert or update of att, excused on public.daily_scores
  for each row execute function public.yk_push_att();

