-- 4. Xabarlar navbati (bir kunda har turdan bittadan)
create table if not exists public.push_queue (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  kind text not null,
  student_id text,
  title text not null,
  body text not null,
  day date not null default (now() at time zone 'Asia/Tashkent')::date,
  status text not null default 'navbat' check (status in ('navbat', 'yuborilmoqda', 'yuborildi', 'xato', 'bekor')),
  tries int not null default 0,
  error text,
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  sent_at timestamptz,
  unique (user_id, kind, student_id, day)
);
alter table public.push_queue drop constraint if exists push_queue_kind_check;
alter table public.push_queue add constraint push_queue_kind_check check (kind in ('keldi', 'kelmadi', 'ketdi', 'test'));
alter table public.push_queue drop constraint if exists push_queue_status_check;
