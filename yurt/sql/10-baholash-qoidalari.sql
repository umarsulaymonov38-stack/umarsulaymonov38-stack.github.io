-- ---------- 1) Baho o'zgarishlari tarixi ----------
create table if not exists public.score_changes (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.students(id) on delete cascade,
  day date not null,
  subject text,
  field text not null,
  old_val text,
  new_val text,
  reason text not null check (length(btrim(reason)) between 3 and 500),
  teacher_id uuid not null default auth.uid(),
  teacher_name text,
  created_at timestamptz not null default now()
);
create index if not exists score_changes_student on public.score_changes (student_id, day);
alter table public.score_changes enable row level security;
drop policy if exists "sc yozish" on public.score_changes;
create policy "sc yozish" on public.score_changes for insert to authenticated
  with check (teacher_id = auth.uid() and public.yk_role() in ('teacher', 'admin'));
drop policy if exists "sc o'qish" on public.score_changes;
create policy "sc o'qish" on public.score_changes for select to authenticated
  using (public.yk_role() = 'admin' or teacher_id = auth.uid() or student_id in (select k.id from public.my_kids() k));
revoke all on public.score_changes from anon;
grant select, insert on public.score_changes to authenticated;

-- ---------- 2) Haftalik "Ota-onaga yaxshilik" so'rovnomasi ----------
create table if not exists public.weekly_kindness (
  student_id uuid not null references public.students(id) on delete cascade,
  week_start date not null,                      -- haftaning dushanbasi
  score smallint not null check (score between 0 and 10),
  answer text,                                   -- xursand qildimi yoki ranjitdimi
  note text check (length(note) <= 500),         -- qanday yaxshilik qildi
  honest boolean not null default false,         -- "vijdonan belgiladim" tasdig'i
  user_id uuid not null default auth.uid(),
  updated_at timestamptz not null default now(),
  primary key (student_id, week_start)
);
alter table public.weekly_kindness enable row level security;
drop policy if exists "wk o'qish" on public.weekly_kindness;
create policy "wk o'qish" on public.weekly_kindness for select to authenticated
  using (public.yk_role() in ('admin', 'teacher') or student_id in (select k.id from public.my_kids() k));
revoke all on public.weekly_kindness from anon;
grant select on public.weekly_kindness to authenticated;

create or replace function public.parent_kindness(p_student uuid, p_score int, p_answer text, p_note text, p_honest boolean)
 returns int
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare t date := (now() at time zone 'Asia/Tashkent')::date; ws date; n int;
begin
  if not exists (select 1 from public.my_kids() k where k.id = p_student) then
    raise exception 'Bu o''quvchi sizning farzandingiz emas' using errcode = '42501'; end if;
  if extract(isodow from t) < 5 then raise exception 'So''rovnoma har hafta juma kuni ochiladi'; end if;
  if not coalesce(p_honest, false) then raise exception 'Iltimos, vijdonan belgilaganingizni tasdiqlang'; end if;
  if p_score not between 0 and 10 then raise exception 'Ball 0–10 oralig''ida bo''lishi kerak'; end if;
  ws := date_trunc('week', t)::date;
  insert into public.weekly_kindness (student_id, week_start, score, answer, note, honest, user_id, updated_at)
  values (p_student, ws, p_score, nullif(btrim(p_answer), ''), nullif(btrim(p_note), ''), true, auth.uid(), now())
  on conflict (student_id, week_start) do update set score = excluded.score, answer = excluded.answer, note = excluded.note,
    honest = true, user_id = excluded.user_id, updated_at = now();
  update public.daily_scores set kindness = p_score
   where student_id = p_student and day between ws and ws + 6 and att = 1;
  get diagnostics n = row_count;
  return n;
end $function$;
revoke all on function public.parent_kindness(uuid, int, text, text, boolean) from public, anon;
grant execute on function public.parent_kindness(uuid, int, text, text, boolean) to authenticated;

-- ---------- 3) Yuqori sinflar: sportsiz hisob (×1.25) va haftalik yaxshilikni kunga yozish ----------
create or replace function public.yurt_upper(p_student uuid)
 returns boolean
 language sql
 stable security definer
 set search_path to 'public'
as $function$
  select coalesce((select c.kind = 'sinf' and coalesce(c.grp, '') = '' and coalesce(c.subject, '') = ''
                          and coalesce(c.grade, nullif(substring(c.name from '^\s*(\d+)'), '')::int, 0) >= 5
                     from public.students s join public.classes c on c.id = s.class_id where s.id = p_student), false)
$function$;

create or replace function public.yurt_daily_fill()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
begin
  -- Ota-ona shu hafta so'rovnomaga javob bergan bo'lsa — kelgan kunga "Ota-onaga yaxshilik" bali yoziladi
  if new.kindness is null and new.att = 1 then
    select w.score into new.kindness from public.weekly_kindness w
     where w.student_id = new.student_id and w.week_start = date_trunc('week', new.day)::date;
  end if;
  -- Yuqori sinflar: sport o'rniga qolgan 4 mezon yig'indisining 25% i (kunlik maksimal 51 saqlanadi)
  if public.yurt_upper(new.student_id) then
    new.sport := case when coalesce(new.book, new.behavior, new.kindness, new.activity) is null then null
                      else round((coalesce(new.book, 0) + coalesce(new.behavior, 0) + coalesce(new.kindness, 0) + coalesce(new.activity, 0)) * 0.25)::int end;
  end if;
  return new;
end $function$;
-- Nomi "a_" bilan boshlanadi: yk_done (yakunlanganini belgilash) dan oldin ishlaydi
drop trigger if exists a_yurt_fill on public.daily_scores;
create trigger a_yurt_fill before insert or update on public.daily_scores for each row execute function public.yurt_daily_fill();

-- Koordinator kunni yakunladi deb hisoblanishi: Ota-onaga yaxshilik (ota-ona belgilaydi), yuqori sinflarda Sport va
-- 1-sinfda Kitob o'qish talab qilinmaydi
create or replace function public.yk_mark_done()
 returns trigger
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare g text; g1 boolean; up boolean; done boolean;
begin
  new.updated_at := now();
  if tg_table_name = 'rep_daily' then
    done := new.att is not null and (new.att = 0 or (new.hw is not null and new.test is not null and new.grade is not null));
  else
    select c.grp into g from public.students s join public.classes c on c.id = s.class_id where s.id = new.student_id;
    if coalesce(g, '') <> '' then
      done := new.att is not null and (new.att = 0 or (new.hw is not null and new.activity is not null and new.behavior is not null));
    else
      g1 := public.yk_g1((select s.class_id from public.students s where s.id = new.student_id));
      up := public.yurt_upper(new.student_id);
      done := new.att is not null and (new.att = 0 or ((g1 or new.book is not null) and (up or new.sport is not null)
              and new.behavior is not null and new.activity is not null));
    end if;
  end if;
  if not done then new.done_at := null;
  elsif new.done_at is null then new.done_at := now();
  end if;
  return new;
end $function$;

