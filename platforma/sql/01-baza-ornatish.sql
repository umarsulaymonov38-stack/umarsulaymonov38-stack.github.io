CREATE OR REPLACE FUNCTION public.class_ranking(p_day date)
 RETURNS TABLE(class_id integer, name text, logo text, teacher_name text, students integer, total integer, pct numeric, has boolean)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  with t as (select c.id cid,c.name cname,c.logo clogo,c.teacher_name tname,case when c.grp is not null then 41 else 51 end mx,
    (select count(*) from students s where s.class_id=c.id and btrim(s.full_name)<>'')::int n,
    coalesce((select sum(coalesce(d.att,0)+coalesce(d.book,0)+coalesce(d.behavior,0)+
      case when c.grp is not null then coalesce(d.hw,0)+coalesce(d.test,0) else coalesce(d.sport,0)+coalesce(d.kindness,0)+coalesce(d.activity,0) end)
      from daily_scores d join students s on s.id=d.student_id where s.class_id=c.id and d.day=p_day),0)::int tot,
    exists(select 1 from daily_scores d join students s on s.id=d.student_id where s.class_id=c.id and d.day=p_day) has
    from classes c where c.kind='sinf')
  select cid,cname,clogo,tname,n,tot,case when n>0 then round(tot::numeric/(n*mx)*100,1) else 0 end,has from t
  where public.my_role()='admin' or (public.my_role()='teacher' and cid in (select public.my_classes())) order by has desc,7 desc$function$
;

