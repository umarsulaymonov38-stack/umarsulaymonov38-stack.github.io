create table if not exists public.parent_checkins (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  student_id uuid references public.students(id) on delete set null,
  day date not null default (now() at time zone 'Asia/Tashkent')::date,
  q smallint,                                   -- savol raqami
  answer text not null check (answer in ('ha', 'yoq')),
  note text check (length(note) <= 500),
  created_at timestamptz not null default now(),
  unique (user_id, day)
);
create index if not exists parent_checkins_day on public.parent_checkins (day);

alter table public.parent_checkins enable row level security;

drop policy if exists "pc o'zini o'qish" on public.parent_checkins;
create policy "pc o'zini o'qish" on public.parent_checkins for select to authenticated
  using (user_id = auth.uid() or public.yk_role() = 'admin');

drop policy if exists "pc o'zi yozish" on public.parent_checkins;
create policy "pc o'zi yozish" on public.parent_checkins for insert to authenticated
  with check (user_id = auth.uid());

drop policy if exists "pc o'zi o'zgartirish" on public.parent_checkins;
create policy "pc o'zi o'zgartirish" on public.parent_checkins for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

revoke all on public.parent_checkins from anon;
grant select, insert, update on public.parent_checkins to authenticated;

notify pgrst, 'reload schema';
